func TestQuietOutputIsOneLine(t *testing.T) {
	r := buildReport("test", []Check{
		ok("a", "first").detail("hidden"),
		ok("b", "second").detail("hidden too"),
	})
	var buf bytes.Buffer
	r.writeText(&buf, false)

	lines := strings.Split(strings.TrimSpace(buf.String()), "\n")
	if len(lines) != 1 {
		t.Fatalf("quiet output has %d lines, want 1:\n%s", len(lines), buf.String())
	}
	if strings.Contains(buf.String(), "hidden") {
		t.Error("details should stay hidden when everything passed")
	}
}

