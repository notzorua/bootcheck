func TestCheckKernelsDetectsMissingDefault(t *testing.T) {
	bootDir, cfg := writeConfig(t)
	touch(t, filepath.Join(bootDir, "kernels"),
		"ccc-linux-7.0.8-bzImage", "ddd-initrd-linux-7.0.8-initrd")

	e := &env{bootDir: bootDir, cfgPath: cfg}
	e.refs, e.refsErr = parseGrubConfig(cfg)

	c := checkKernels(e)
	if c.Status != StatusFail {
		t.Fatalf("status = %q, want fail", c.Status)
	}
	if !strings.Contains(strings.Join(c.Details, "\n"), "grub> prompt") {
		t.Error("a broken default entry should be called out explicitly")
	}
}

