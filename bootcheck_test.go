func TestReportStatusPrecedence(t *testing.T) {
	cases := []struct {
		checks []Check
		want   Status
		safe   bool
	}{
		{[]Check{ok("a", "x")}, StatusOK, true},
		{[]Check{ok("a", "x"), skip("b", "y")}, StatusOK, true},
		{[]Check{ok("a", "x"), warn("b", "y")}, StatusWarn, true},
		{[]Check{warn("a", "x"), fail("b", "y")}, StatusFail, false},
	}
	for i, c := range cases {
		r := buildReport("test", c.checks)
		if r.Status != c.want || r.SafeToReboot != c.safe {
			t.Errorf("case %d: status %q safe %v, want %q %v",
				i, r.Status, r.SafeToReboot, c.want, c.safe)
		}
	}
}

func TestJSONIsValidAndComplete(t *testing.T) {
	r := buildReport("test", []Check{
		ok("a", "fine"),
		warn("b", "hmm").detail("why").data("bytes", 42),
	})
	var buf bytes.Buffer
	if err := r.writeJSON(&buf); err != nil {
		t.Fatal(err)
	}

	var back Report
	if err := json.Unmarshal(buf.Bytes(), &back); err != nil {
		t.Fatalf("output is not valid JSON: %v", err)
	}
	if back.Status != StatusWarn || len(back.Checks) != 2 {
		t.Errorf("round trip lost information: %+v", back)
	}
	if back.Checks[1].Data["bytes"] != float64(42) {
		t.Errorf("attached data did not survive: %v", back.Checks[1].Data)
	}
}

