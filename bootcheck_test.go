func writeConfig(t *testing.T) (bootDir, cfg string) {
	t.Helper()
	bootDir = t.TempDir()
	if err := os.MkdirAll(filepath.Join(bootDir, "grub"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(bootDir, "kernels"), 0o755); err != nil {
		t.Fatal(err)
	}
	cfg = filepath.Join(bootDir, "grub", "grub.cfg")
	if err := os.WriteFile(cfg, []byte(sampleConfig), 0o644); err != nil {
		t.Fatal(err)
	}
	return bootDir, cfg
}

func touch(t *testing.T, dir string, names ...string) {
	t.Helper()
	for _, n := range names {
		if err := os.WriteFile(filepath.Join(dir, n), []byte("x"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestEspPath(t *testing.T) {
	cases := map[string]string{
		"($drive1)//kernels/abc": "/kernels/abc",
		"(hd0,1)/kernels/abc":    "/kernels/abc",
		"//kernels/abc":          "/kernels/abc",
		"kernels/abc":            "/kernels/abc",
		"($drive1)//":            "",
		"($drive1":               "",
	}
	for in, want := range cases {
		if got := espPath(in); got != want {
			t.Errorf("espPath(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestParseGrubConfigDeduplicates(t *testing.T) {
	_, cfg := writeConfig(t)
	refs, err := parseGrubConfig(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if len(refs) != 4 {
		t.Fatalf("got %d unique files, want 4", len(refs))
	}
	if n := len(refs[0].entries); n != 2 {
		t.Errorf("the shared kernel is referenced by %d entries, want 2", n)
	}
}

