func TestMenuLayoutSeparatesProfileSubmenus(t *testing.T) {
	dir := t.TempDir()
	cfg := filepath.Join(dir, "grub.cfg")
	if err := os.WriteFile(cfg, []byte(configWithProfiles), 0o644); err != nil {
		t.Fatal(err)
	}

	layout, err := readMenuLayout(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if layout.main != 2 {
		t.Errorf("top level entries = %d, want 2", layout.main)
	}
	if layout.profileTotal() != 2 {
		t.Errorf("profile entries = %d, want 2", layout.profileTotal())
	}
	want := []string{"hyperland", "hyperland2"}
	if got := layout.profileNames(); !reflect.DeepEqual(got, want) {
		t.Errorf("profile names = %v, want %v", got, want)
	}
}

